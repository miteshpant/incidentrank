import type { ControlDefinition } from "@incidentrank/simulator";

/** Pauses the background batch/compaction job entirely. The fastest way
 * to relieve storage IOPS pressure, but every minute it stays paused the
 * batch job's own backlog grows — it does not run for free. */
export const BACKGROUND_WORKLOAD_PAUSED_KEY = "backgroundWorkloadPaused";

/** How many batch worker threads run concurrently when the workload is
 * NOT fully paused. Lower concurrency trades batch throughput for lower
 * storage IOPS consumption — a partial, tunable version of pausing
 * outright rather than an all-or-nothing switch. */
export const BATCH_CONCURRENCY_KEY = "batchConcurrency";

/** How often the database flushes dirty pages to persistent storage.
 * Lowering checkpoint frequency (longer interval) reduces steady-state
 * write IOPS, but widens the crash-recovery replay window — a real
 * durability-adjacent tradeoff, not a free lever. */
export const CHECKPOINT_FREQUENCY_SECONDS_KEY = "checkpointFrequencySeconds";

/** The persistent storage volume's provisioning tier. Upgrading to
 * provisioned IOPS raises the ceiling the whole stack (batch workload
 * included) can draw from, at real ongoing infrastructure cost — a
 * genuine capacity fix rather than a tradeoff against another
 * subsystem. */
export const STORAGE_TIER_KEY = "storageTier";

/** Ceiling on concurrent queries the API layer is allowed to issue
 * against the database. Lowering it reduces how much read load reaches
 * an already-saturated storage layer, but throttled requests queue (or
 * get rejected) at the API edge instead — the cost moves, it does not
 * disappear. */
export const QUERY_CONCURRENCY_LIMIT_KEY = "queryConcurrencyLimit";

/** Read-through cache in front of the database. Absorbs repeat reads and
 * helps read latency specifically, but has no effect on the write IOPS
 * generated by checkpoint flushes or the background batch job. */
export const READ_CACHE_ENABLED_KEY = "readCacheEnabled";

export const controls: ControlDefinition[] = [
  {
    key: BACKGROUND_WORKLOAD_PAUSED_KEY,
    allowedValues: [false, true],
    initialValue: false,
  },
  {
    key: BATCH_CONCURRENCY_KEY,
    allowedValues: [8, 4, 2, 1],
    initialValue: 8,
  },
  {
    key: CHECKPOINT_FREQUENCY_SECONDS_KEY,
    allowedValues: [30, 60, 180, 300],
    initialValue: 30,
  },
  {
    key: STORAGE_TIER_KEY,
    allowedValues: ["standard", "provisioned-iops"],
    initialValue: "standard",
  },
  {
    key: QUERY_CONCURRENCY_LIMIT_KEY,
    allowedValues: [200, 100, 50],
    initialValue: 200,
  },
  {
    key: READ_CACHE_ENABLED_KEY,
    allowedValues: [false, true],
    initialValue: false,
  },
];
